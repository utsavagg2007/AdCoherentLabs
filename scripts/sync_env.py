"""sync_env.py — regenerate the project's env files from one source of truth.

    python scripts/sync_env.py [--stack-dir C:\\Users\\HP\\supabase-project]
                               [--only root,frontend] [--allow-defaults]

The project deliberately has just TWO env files:

    .env                 the WHOLE backend + engine (api, worker, scheduler,
                         all four engine layers, RAG store, credits, billing)
    frontend/.env.local  the Next.js app (public NEXT_PUBLIC_* values only)

Secrets live once, in the self-hosted Supabase stack's own ``.env``
(POSTGRES_PASSWORD, JWT_SECRET, ANON/SERVICE keys). This tool reads that stack
env, finds the password the database *actually accepts* (probing, so a
half-finished rotation is caught instead of silently breaking retrieval), and
regenerates the two files above. Run it after any secret rotation.

The root ``.env`` holds HOST endpoints (127.0.0.1). Inside the compose network
the backend containers reach the stack by service name; that switch happens in
``backend/docker-entrypoint.sh`` (APP_IN_CONTAINER=1), NOT in a second env file.

Prints fingerprints only — never secret values.
"""

from __future__ import annotations

import argparse
import hashlib
import secrets as pysecrets
import sys
import urllib.parse
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPTS_DIR.parent
FRONTEND_ROOT = PROJECT_ROOT / "frontend"
DEFAULT_STACK = Path(r"C:\Users\HP\supabase-project")
SOCAT_PORT = 54322          # adcoherent-rag-db-proxy 127.0.0.1:54322 -> supabase-db:5432

STACK_KEYS = ("JWT_SECRET", "ANON_KEY", "SERVICE_ROLE_KEY", "POSTGRES_PASSWORD")


def parse_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, _, v = s.partition("=")
        out[k.strip()] = v.strip().strip('"')
    return out


def fp(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()[:12] if value else "(empty)"


def _db_accepts(password: str, port: int = SOCAT_PORT) -> bool:
    try:
        import psycopg
    except ImportError:
        return True   # cannot probe without psycopg; assume caller knows
    try:
        with psycopg.connect(host="127.0.0.1", port=port, user="postgres",
                             password=password, dbname="postgres",
                             connect_timeout=5):
            return True
    except Exception:
        return False


def resolve_working_db_password(stack_dir: Path, intended: str) -> tuple[str, str]:
    """(password, state): 'clean' (matches the stack .env), 'drift' (a backup
    password still works — rotation not finished on the DB), or 'unknown'."""
    if _db_accepts(intended):
        return intended, "clean"
    for bak in sorted(stack_dir.glob(".env.bak-*"), reverse=True):
        cand = parse_env(bak).get("POSTGRES_PASSWORD", "")
        if cand and cand != intended and _db_accepts(cand):
            return cand, "drift"
    if _db_accepts("your-super-secret-and-long-postgres-password"):
        return "your-super-secret-and-long-postgres-password", "drift"
    return intended, "unknown"


def _socat_url(password: str) -> str:
    return (f"postgresql://postgres:{urllib.parse.quote(password, safe='')}"
            f"@127.0.0.1:{SOCAT_PORT}/postgres")


# ---------------------------------------------------------------------------

def write_root_env(stack_env: dict, pw: str, prev_root: dict,
                   prev_backend: dict) -> Path:
    """The single backend+engine env. Host endpoints; the container entrypoint
    swaps them for service names."""
    def pick(key: str, default: str = "") -> str:
        return prev_root.get(key) or prev_backend.get(key) or default

    url = _socat_url(pw)
    redis_pw = pick("REDIS_PASSWORD") or pysecrets.token_hex(16)
    issuer = (stack_env.get("API_EXTERNAL_URL", "http://localhost:8000").rstrip("/")
              + "/auth/v1")
    lines = [
        "# .env - THE single env for the whole backend + engine.",
        "# GENERATED by scripts/sync_env.py; DO NOT COMMIT (gitignored).",
        "# Host endpoints (127.0.0.1); backend/docker-entrypoint.sh swaps them",
        "# for supabase-db / supabase-kong / redis inside the compose network.",
        f"APP_ENV={pick('APP_ENV', 'dev')}",
        f"LOG_LEVEL={pick('LOG_LEVEL', 'info')}",
        "",
        "# -- data plane (Supabase) --",
        "SUPABASE_URL=http://127.0.0.1:8000",
        f"SUPABASE_SERVICE_ROLE_KEY={stack_env['SERVICE_ROLE_KEY']}",
        f"SUPABASE_JWT_SECRET={stack_env['JWT_SECRET']}",
        f"SUPABASE_JWT_ISSUER={issuer}",
        f"POSTGRES_PASSWORD={pw}",
        f"SUPABASE_DB_URL={url}",
        f"DATABASE_URL={url}",           # engine RAG store + saas data plane
        f"DATABASE_URL_API={url}",
        f"DATABASE_URL_WORKER={url}",
        f"DATABASE_URL_MIGRATIONS={url}",
        "# prod: DATABASE_URL_API -> pooler :6543 (txn), DATABASE_URL_WORKER -> :5432 (session)",
        "",
        "# -- LLM providers (server only) --",
        f"OPENROUTER_API_KEY={pick('OPENROUTER_API_KEY')}",
        f"ANTHROPIC_API_KEY={pick('ANTHROPIC_API_KEY')}",
        "# free/hobby model overrides (defaults live in review/tiers.py):",
        "# OPENROUTER_FREE_MODEL=qwen/qwen3.7-plus",
        "# OPENROUTER_HOBBY_MODEL=qwen/qwen3.7-max",
        "",
        "# -- engine: OCR (Layer 1) + embeddings (Layer 3) --",
        f"OCR_TIER={pick('OCR_TIER', 'free')}",
        f"EMBEDDING_MODEL_NAME={pick('EMBEDDING_MODEL_NAME', 'sentence-transformers/all-MiniLM-L6-v2')}",
        f"EMBEDDING_DIM={pick('EMBEDDING_DIM', '384')}",
        "",
        "# -- app (rate limits, uploads, retention) --",
        f"CORS_ALLOWED_ORIGINS={pick('CORS_ALLOWED_ORIGINS', 'http://localhost:3000')}",
        f"REDIS_PASSWORD={redis_pw}",
        f"REDIS_URL=redis://:{redis_pw}@127.0.0.1:6379/0",
        "CLAMAV_HOST=127.0.0.1",
        "CLAMAV_PORT=3310",
        f"CLAMAV_REQUIRED={pick('CLAMAV_REQUIRED', 'true')}",
        f"ADMIN_EMAILS={pick('ADMIN_EMAILS')}",
        f"RETENTION_DRY_RUN={pick('RETENTION_DRY_RUN', 'true')}",
        "",
        "# -- billing (fill from the Stripe dashboard) --",
    ]
    for k in ("STRIPE_SECRET_KEY", "STRIPE_WEBHOOK_SECRET", "STRIPE_PRICE_HOBBY",
              "STRIPE_PRICE_PRO", "STRIPE_PRICE_DESIGN", "STRIPE_PRICE_ENTERPRISE",
              "STRIPE_PRICE_PACK_STARTER", "STRIPE_PRICE_PACK_GROWTH",
              "STRIPE_PRICE_PACK_SCALE"):
        lines.append(f"{k}={pick(k)}")
    lines += ["", "# -- ops --",
              f"SENTRY_DSN={pick('SENTRY_DSN')}",
              f"METRICS_BASIC_AUTH={pick('METRICS_BASIC_AUTH')}"]
    out = PROJECT_ROOT / ".env"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_frontend_env(stack_env: dict, prev_frontend: dict) -> Path:
    """frontend/.env.local — public browser config only. The anon key comes
    from the stack .env (the source of truth): after a rotation the old key
    is dead at Kong, so preserving it would silently break frontend logins
    (this bit us on 2026-07-20). A differing previous key is reported."""
    stack_anon = stack_env.get("ANON_KEY", "")
    prev_anon = prev_frontend.get("NEXT_PUBLIC_SUPABASE_ANON_KEY", "")
    anon = stack_anon or prev_anon
    if prev_anon and stack_anon and prev_anon != stack_anon:
        print(f"  NOTE: frontend anon key replaced (was fp {fp(prev_anon)}, "
              f"stack fp {fp(stack_anon)}) - restart the Next.js dev server. "
              "If the stack was NOT restarted after its .env changed, restart "
              "it or this key will not match the running GoTrue.")
    lines = [
        "# frontend/.env.local - THE single env for the Next.js app.",
        "# GENERATED by scripts/sync_env.py; DO NOT COMMIT (gitignored).",
        "# Public, browser-safe values only - never a service key or DB password.",
        f"NEXT_PUBLIC_SUPABASE_URL={prev_frontend.get('NEXT_PUBLIC_SUPABASE_URL', 'http://localhost:8000')}",
        f"NEXT_PUBLIC_SUPABASE_ANON_KEY={anon}",
        f"NEXT_PUBLIC_API_URL={prev_frontend.get('NEXT_PUBLIC_API_URL', 'http://localhost:8080')}",
    ]
    out = FRONTEND_ROOT / ".env.local"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def run(stack_dir: Path = DEFAULT_STACK, only: set[str] | None = None,
        allow_defaults: bool = False, force_local: bool = False) -> int:
    only = only or {"root", "frontend"}

    # This script's whole job is to copy the SELF-HOSTED stack's secrets into
    # the two env files. Once the project points at Supabase Cloud that is
    # destructive: it would silently overwrite the cloud URLs, service key and
    # JWT secret with local ones, and the app would come back up talking to a
    # stack that is no longer the source of truth.
    if not force_local:
        current = parse_env(PROJECT_ROOT / ".env")
        if current.get("SUPABASE_MODE", "local").lower() == "cloud":
            print("REFUSING: .env has SUPABASE_MODE=cloud.\n"
                  "This script writes SELF-HOSTED stack credentials and would clobber\n"
                  "the cloud URL / service key / JWT secret / pooler DB URL.\n"
                  "To move back to the local stack: set SUPABASE_MODE=local (or restore\n"
                  ".env.local-stack.bak), then re-run. Override: --force-local.",
                  file=sys.stderr)
            return 3

    stack_env = parse_env(stack_dir / ".env")
    missing = [k for k in STACK_KEYS if not stack_env.get(k)]
    if missing:
        print(f"error: stack .env at {stack_dir} is missing {missing}", file=sys.stderr)
        return 1

    intended = stack_env["POSTGRES_PASSWORD"]
    defaults_present = "your-super-secret" in (stack_env.get("JWT_SECRET", "") + intended)
    if defaults_present and not allow_defaults:
        print("REFUSING: the stack .env still carries PUBLIC DEFAULT secrets.\n"
              "Run  python supabase/harden.py  first (spec P0), then re-run this.\n"
              "Throwaway dev only: --allow-defaults.", file=sys.stderr)
        return 2

    pw, state = ("", "skipped")
    if "root" in only:
        pw, state = resolve_working_db_password(stack_dir, intended)
        if state == "unknown":
            print("WARNING: no known password connects to the DB via socat :54322 - "
                  "writing the stack .env password anyway; retrieval will fail until "
                  "the DB role matches. Is the stack up?", file=sys.stderr)

    prev_root = parse_env(PROJECT_ROOT / ".env")
    prev_backend = parse_env(PROJECT_ROOT / "backend" / ".env")   # legacy, if still around
    prev_frontend = parse_env(FRONTEND_ROOT / ".env.local")
    if not prev_frontend:                       # first run: seed from old files
        prev_frontend = parse_env(FRONTEND_ROOT / ".env") or parse_env(FRONTEND_ROOT / ".env.example")

    written = []
    if "root" in only:
        written.append(write_root_env(stack_env, pw, prev_root, prev_backend))
    if "frontend" in only:
        written.append(write_frontend_env(stack_env, prev_frontend))

    print("sync_env: wrote " + ", ".join(str(p.relative_to(PROJECT_ROOT)) for p in written))
    if "root" in only:
        print(f"  DB password used   fp {fp(pw)}  (state: {state})")
    print(f"  JWT_SECRET         fp {fp(stack_env['JWT_SECRET'])}")
    print(f"  SERVICE_ROLE_KEY   fp {fp(stack_env['SERVICE_ROLE_KEY'])}")
    if state == "drift":
        print("\n  *** ROTATION INCOMPLETE ***\n"
              "  The DB still accepts an OLDER password than the stack .env claims.\n"
              "  The repo now points at the working (older) password so the engine\n"
              "  runs, but the rotation is NOT applied to the DB (and the stack's\n"
              "  auth/rest/storage may be crashlooping). Finish it on the live stack\n"
              "  (ALTER ROLE + docker compose up -d, or re-run supabase/harden.py),\n"
              "  then re-run this tool. See AUTH_AUDIT_AND_PLAN.md / supabase.md.")
    if defaults_present:
        print("\n  NOTE: writing from PUBLIC DEFAULT secrets (dev). Run harden.py before launch.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Regenerate the project's two env files from the stack .env.")
    ap.add_argument("--stack-dir", type=Path, default=DEFAULT_STACK)
    ap.add_argument("--only", default="root,frontend",
                    help="comma list of targets: root,frontend")
    ap.add_argument("--allow-defaults", action="store_true",
                    help="permit writing dev env from the PUBLIC default secrets")
    ap.add_argument("--force-local", action="store_true",
                    help="write self-hosted credentials even when .env is in cloud mode "
                         "(destructive: overwrites the cloud data-plane values)")
    args = ap.parse_args()
    only = {t.strip() for t in args.only.split(",") if t.strip()}
    return run(args.stack_dir, only, args.allow_defaults, args.force_local)


if __name__ == "__main__":
    sys.exit(main())
