"""sync_env.py — regenerate EVERY repo .env from one source of truth.

    python scripts/sync_env.py [--stack-dir C:\\Users\\HP\\supabase-project]
                               [--only root,rag,backend] [--allow-defaults]

Why this exists
---------------
Secrets live in the self-hosted Supabase stack's own ``.env`` (POSTGRES_PASSWORD,
JWT_SECRET, ANON/SERVICE keys). Four *derived* env files in this repo embed
pieces of them:

    .env                 engine + RAG: DATABASE_URL, provider keys, OCR
    rag-engine/.env      RAG store: DATABASE_URL, embedding config
    backend/.env         the whole backend (api/worker/scheduler)
    CV-RULE_ENG-NLP/.env optional OCR settings (left untouched)

Hand-editing four files after every secret rotation is how they drift — which
is exactly what broke RAG retrieval on 2026-07-14: ``harden.py`` rewrote the
files with a new password the running database had not actually adopted, so
every DB connection got ``password authentication failed`` and the engine
degraded to empty retrieval.

This tool makes all derived files DERIVED again: it reads the stack .env, finds
the password the database *actually accepts* (probing, so a half-finished
rotation is detected instead of silently breaking things), and regenerates the
repo env files consistently. Run it once after any rotation and the drift class
of bug is gone.

Prints fingerprints only — never secret values.
"""

from __future__ import annotations

import argparse
import hashlib
import secrets as pysecrets
import sys
import urllib.parse
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPTS_DIR.parent
BACKEND_ROOT = PROJECT_ROOT / "backend"
RAG_ROOT = PROJECT_ROOT / "rag-engine"
DEFAULT_STACK = Path(r"C:\Users\HP\supabase-project")
SOCAT_PORT = 54322          # adcoherent-rag-db-proxy 127.0.0.1:54322 -> supabase-db:5432

STACK_KEYS = ("JWT_SECRET", "ANON_KEY", "SERVICE_ROLE_KEY", "POSTGRES_PASSWORD")
_BACKEND_PRESERVE = ("STRIPE_", "ADMIN_EMAILS", "SENTRY_", "CORS_", "APP_ENV",
                     "REDIS_PASSWORD", "RETENTION_DRY_RUN", "CLAMAV_REQUIRED",
                     "METRICS_")


def parse_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, _, v = s.partition("=")
        out[k.strip()] = v.strip().strip('"')
    return out


def fp(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()[:12] if value else "(empty)"


def _db_accepts(password: str, port: int = SOCAT_PORT) -> bool:
    try:
        import psycopg
    except ImportError:
        return True   # cannot probe without psycopg; assume caller knows
    try:
        with psycopg.connect(host="127.0.0.1", port=port, user="postgres",
                             password=password, dbname="postgres",
                             connect_timeout=5):
            return True
    except Exception:
        return False


def resolve_working_db_password(stack_dir: Path, intended: str) -> tuple[str, str]:
    """(password, state) where state is 'clean' (matches the stack .env),
    'drift' (a pre-harden backup password still works — rotation is not
    finished on the DB), or 'unknown' (nothing we know of connects)."""
    if _db_accepts(intended):
        return intended, "clean"
    # Rotation half-applied: the stack .env was updated but the DB role was
    # not. Fall back to any backup password the DB still accepts so the engine
    # keeps working, and flag it loudly.
    for bak in sorted(stack_dir.glob(".env.bak-*"), reverse=True):
        cand = parse_env(bak).get("POSTGRES_PASSWORD", "")
        if cand and cand != intended and _db_accepts(cand):
            return cand, "drift"
    if _db_accepts("your-super-secret-and-long-postgres-password"):
        return "your-super-secret-and-long-postgres-password", "drift"
    return intended, "unknown"


def _socat_url(password: str) -> str:
    return (f"postgresql://postgres:{urllib.parse.quote(password, safe='')}"
            f"@127.0.0.1:{SOCAT_PORT}/postgres")


# ---------------------------------------------------------------------------
# File writers — each returns the fingerprint lines to print.

def write_root_env(pw: str, root_prev: dict) -> Path:
    url = _socat_url(pw)
    lines = [
        "# .env - GENERATED by scripts/sync_env.py; DO NOT COMMIT real keys.",
        "# The engine package loads THIS first (override=False); a real",
        "# DATABASE_URL must live here or it shadows rag-engine/.env with ''.",
        "",
        "# ----- Layer 3: LLM providers -----",
        f"OPENROUTER_API_KEY={root_prev.get('OPENROUTER_API_KEY', '')}",
        f"ANTHROPIC_API_KEY={root_prev.get('ANTHROPIC_API_KEY', '')}",
        "# Free/hobby model overrides (defaults live in review/tiers.py):",
        "# OPENROUTER_FREE_MODEL=qwen/qwen3.7-plus",
        "# OPENROUTER_HOBBY_MODEL=qwen/qwen3.7-max",
        "",
        "# ----- Layer 3: RAG store + SaaS data plane (socat direct :54322) -----",
        f"DATABASE_URL={url}",
        "",
        "# ----- Layer 1: OCR -----",
        f"OCR_TIER={root_prev.get('OCR_TIER', 'free')}",
    ]
    for k in ("EMBEDDING_MODEL_NAME", "EMBEDDING_DIM", "EMBEDDING_FAKE",
              "GOOGLE_APPLICATION_CREDENTIALS"):
        if root_prev.get(k):
            lines.append(f"{k}={root_prev[k]}")
    out = PROJECT_ROOT / ".env"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_rag_env(pw: str, rag_prev: dict) -> Path:
    url = _socat_url(pw)
    lines = [
        "# rag-engine/.env - GENERATED by scripts/sync_env.py; DO NOT COMMIT.",
        f"DATABASE_URL={url}",
        f"EMBEDDING_MODEL_NAME={rag_prev.get('EMBEDDING_MODEL_NAME', 'sentence-transformers/all-MiniLM-L6-v2')}",
        f"EMBEDDING_DIM={rag_prev.get('EMBEDDING_DIM', '384')}",
    ]
    if rag_prev.get("EMBEDDING_FAKE"):
        lines.append(f"EMBEDDING_FAKE={rag_prev['EMBEDDING_FAKE']}")
    out = RAG_ROOT / ".env"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_backend_env(stack_env: dict, pw: str, backend_prev: dict,
                      root_prev: dict) -> tuple[Path, str]:
    preserved = {k: v for k, v in backend_prev.items()
                 if k.startswith(_BACKEND_PRESERVE) and v}
    redis_pw = preserved.get("REDIS_PASSWORD") or pysecrets.token_hex(16)
    url = _socat_url(pw)
    issuer = (stack_env.get("API_EXTERNAL_URL", "http://localhost:8000").rstrip("/")
              + "/auth/v1")
    lines = [
        "# backend/.env - GENERATED by scripts/sync_env.py; DO NOT COMMIT.",
        "# Host-dev values; docker-compose.backend.yml overrides in-network endpoints.",
        f"APP_ENV={preserved.get('APP_ENV', 'dev')}",
        "",
        "# -- data plane --",
        "SUPABASE_URL=http://127.0.0.1:8000",
        f"SUPABASE_SERVICE_ROLE_KEY={stack_env['SERVICE_ROLE_KEY']}",
        f"SUPABASE_JWT_SECRET={stack_env['JWT_SECRET']}",
        f"SUPABASE_JWT_ISSUER={issuer}",
        f"POSTGRES_PASSWORD={pw}",
        f"SUPABASE_DB_URL={url}",
        f"DATABASE_URL_API={url}",
        f"DATABASE_URL_WORKER={url}",
        f"DATABASE_URL_MIGRATIONS={url}",
        "# prod: DATABASE_URL_API -> pooler :6543 (txn), DATABASE_URL_WORKER -> :5432 (session)",
        "",
        "# -- app --",
        f"CORS_ALLOWED_ORIGINS={preserved.get('CORS_ALLOWED_ORIGINS', 'http://localhost:3000')}",
        f"REDIS_PASSWORD={redis_pw}",
        f"REDIS_URL=redis://:{redis_pw}@127.0.0.1:6379/0",
        "CLAMAV_HOST=127.0.0.1",
        "CLAMAV_PORT=3310",
        f"CLAMAV_REQUIRED={preserved.get('CLAMAV_REQUIRED', 'true')}",
        f"ADMIN_EMAILS={preserved.get('ADMIN_EMAILS', '')}",
        f"RETENTION_DRY_RUN={preserved.get('RETENTION_DRY_RUN', 'true')}",
        "",
        "# -- providers (server only) --",
        f"ANTHROPIC_API_KEY={preserved.get('ANTHROPIC_API_KEY') or root_prev.get('ANTHROPIC_API_KEY', '')}",
        f"OPENROUTER_API_KEY={preserved.get('OPENROUTER_API_KEY') or root_prev.get('OPENROUTER_API_KEY', '')}",
        "",
        "# -- billing (fill from the Stripe dashboard) --",
    ]
    for k in ("STRIPE_SECRET_KEY", "STRIPE_WEBHOOK_SECRET", "STRIPE_PRICE_HOBBY",
              "STRIPE_PRICE_PRO", "STRIPE_PRICE_DESIGN", "STRIPE_PRICE_ENTERPRISE",
              "STRIPE_PRICE_PACK_STARTER", "STRIPE_PRICE_PACK_GROWTH",
              "STRIPE_PRICE_PACK_SCALE"):
        lines.append(f"{k}={preserved.get(k, '')}")
    lines += ["", "# -- ops --",
              f"SENTRY_DSN={preserved.get('SENTRY_DSN', '')}",
              f"METRICS_BASIC_AUTH={preserved.get('METRICS_BASIC_AUTH', '')}"]
    out = BACKEND_ROOT / ".env"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out, redis_pw


def run(stack_dir: Path = DEFAULT_STACK, only: set[str] | None = None,
        allow_defaults: bool = False) -> int:
    only = only or {"root", "rag", "backend"}
    stack_env = parse_env(stack_dir / ".env")
    missing = [k for k in STACK_KEYS if not stack_env.get(k)]
    if missing:
        print(f"error: stack .env at {stack_dir} is missing {missing}", file=sys.stderr)
        return 1

    intended = stack_env["POSTGRES_PASSWORD"]
    defaults_present = "your-super-secret" in (stack_env.get("JWT_SECRET", "") + intended)
    if defaults_present and not allow_defaults:
        print("REFUSING: the stack .env still carries PUBLIC DEFAULT secrets.\n"
              "Run  python supabase/harden.py  first (spec P0), then re-run this.\n"
              "Throwaway dev only: --allow-defaults.", file=sys.stderr)
        return 2

    pw, state = resolve_working_db_password(stack_dir, intended)
    if state == "unknown":
        print("WARNING: no known password connects to the DB via socat :54322 - "
              "writing the stack .env password anyway; the engine will fail to "
              "retrieve until the DB role matches. Is the stack up?", file=sys.stderr)

    root_prev = parse_env(PROJECT_ROOT / ".env")
    rag_prev = parse_env(RAG_ROOT / ".env")
    backend_prev = parse_env(BACKEND_ROOT / ".env")

    written = []
    if "root" in only:
        written.append(write_root_env(pw, root_prev))
    if "rag" in only:
        written.append(write_rag_env(pw, rag_prev))
    redis_pw = None
    if "backend" in only:
        p, redis_pw = write_backend_env(stack_env, pw, backend_prev, root_prev)
        written.append(p)

    print("sync_env: wrote " + ", ".join(str(p.relative_to(PROJECT_ROOT)) for p in written))
    print(f"  DB password used   fp {fp(pw)}  (state: {state})")
    print(f"  JWT_SECRET         fp {fp(stack_env['JWT_SECRET'])}")
    print(f"  SERVICE_ROLE_KEY   fp {fp(stack_env['SERVICE_ROLE_KEY'])}")
    if redis_pw:
        print(f"  REDIS_PASSWORD     fp {fp(redis_pw)}")
    if state == "drift":
        print("\n  *** ROTATION INCOMPLETE ***\n"
              "  The DB role still accepts an OLDER password than the stack .env\n"
              "  claims. The repo now points at the working (older) password so the\n"
              "  engine runs, but the intended rotation is NOT applied to the DB.\n"
              "  Finish it on the live stack, then re-run this tool:\n"
              "    (in the stack dir) ALTER ROLE postgres/other roles to the new pw\n"
              "    + docker compose up -d, or re-run supabase/harden.py.\n"
              "  See AUTH_AUDIT_AND_PLAN.md / supabase.md for the exact steps.")
    if defaults_present:
        print("\n  NOTE: writing from PUBLIC DEFAULT secrets (dev). Run harden.py before launch.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Regenerate all repo .env files from the stack .env.")
    ap.add_argument("--stack-dir", type=Path, default=DEFAULT_STACK)
    ap.add_argument("--only", default="root,rag,backend",
                    help="comma list of targets: root,rag,backend")
    ap.add_argument("--allow-defaults", action="store_true",
                    help="permit writing dev env from the PUBLIC default secrets")
    args = ap.parse_args()
    only = {t.strip() for t in args.only.split(",") if t.strip()}
    return run(args.stack_dir, only, args.allow_defaults)


if __name__ == "__main__":
    sys.exit(main())
