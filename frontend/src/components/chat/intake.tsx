"use client";

/**
 * The two things the review needs from you before it can start, asked one at a
 * time instead of sitting on a form as optional fields nobody filled in.
 *
 * Both are real engine inputs, not interview flavour:
 *   · jurisdictions  → `target_jurisdictions`, which changes framework routing
 *                      (state UDAP coverage on top of the federal frameworks).
 *   · substantiation → `human_guidance` on review_and_verify, injected into the
 *                      Layer 3 prompt as authoritative operator direction. It
 *                      is the same channel a reviewer's resume guidance uses.
 *
 * These two questions are authored by the product, not generated by a model —
 * the copy says "Before I start" rather than implying analysis has happened.
 * The model's own questions arrive later, when a run lands in human_review.
 */

import { useState } from "react";
import { MapPin, ShieldQuestion } from "lucide-react";
import { JurisdictionSelect } from "@/components/app/jurisdiction-select";
import { TurnCard } from "@/components/chat/turn";
import { Button } from "@/components/ui/button";
import type { SpottedClaim } from "@/lib/claims";

export function JurisdictionQuestion({
  onAnswer,
}: {
  onAnswer: (codes: string[]) => void;
}) {
  const [selected, setSelected] = useState<string[]>([]);

  return (
    <>
      <p>
        Before I start — <strong className="text-strong">where will this
        run?</strong> State targeting adds that state&apos;s UDAP rules on top
        of the federal frameworks, so it changes what I check.
      </p>
      <TurnCard tone="asking">
        <div className="flex items-start gap-2.5">
          <MapPin className="mt-0.5 size-4 shrink-0 text-brand-text" aria-hidden />
          <div className="min-w-0 flex-1">
            <JurisdictionSelect selected={selected} onChange={setSelected} />
          </div>
        </div>
        <div className="mt-4 flex flex-wrap gap-2.5">
          <Button
            size="sm"
            onClick={() => onAnswer(selected)}
            disabled={selected.length === 0}
          >
            {selected.length === 0
              ? "Select states"
              : `Use ${selected.length} state${selected.length === 1 ? "" : "s"}`}
          </Button>
          <Button variant="secondary" size="sm" onClick={() => onAnswer([])}>
            Runs nationwide
          </Button>
        </div>
      </TurnCard>
    </>
  );
}

/**
 * Semicolons, not "and": the individual asks already contain "and", so an
 * and-join produced "the terms it assumes and the data and time period…".
 */
function joinAsks(asks: string[]): string {
  return asks.length > 0 ? asks.join("; ") : "supporting evidence";
}

export function SubstantiationQuestion({
  claims,
  onAnswer,
}: {
  claims: SpottedClaim[];
  onAnswer: (substantiation: string | null) => void;
}) {
  const [value, setValue] = useState("");

  return (
    <>
      {claims.length > 0 ? (
        <>
          <p>
            I spotted{" "}
            {claims.length === 1 ? "a claim" : `${claims.length} claims`} that a
            regulator would expect you to be able to back up.{" "}
            <strong className="text-strong">What supports them?</strong>
          </p>
          <ul className="mt-3 space-y-3">
            {claims.map((c, i) => (
              <li key={i} className="border-l-2 border-brand-line pl-3">
                <p className="text-[13.5px] text-strong">
                  &ldquo;{c.text}&rdquo;
                </p>
                <p className="text-[12.5px] text-subtle">
                  Needs {joinAsks(c.asks)}.
                </p>
              </li>
            ))}
          </ul>

        </>
      ) : (
        <p>
          <strong className="text-strong">
            Is there evidence I should review alongside this?
          </strong>{" "}
          Rate sources, study citations, the terms behind an offer — anything
          that substantiates what the creative says.
        </p>
      )}

      <TurnCard tone="asking">
        <label
          htmlFor="substantiation"
          className="mb-1.5 flex items-center gap-2 text-[13px] font-semibold text-brand-text"
        >
          <ShieldQuestion className="size-4" aria-hidden />
          Substantiation
        </label>
        <textarea
          id="substantiation"
          className="input min-h-28 resize-y bg-surface leading-relaxed"
          placeholder={
            claims.length > 0
              ? "The 3.9% APR is our advertised floor rate for 780+ FICO on 36-month terms, effective 1 Aug — rate sheet RS-2026-08."
              : "Rate sheets, study citations, offer terms, prior legal sign-off…"
          }
          value={value}
          onChange={(e) => setValue(e.target.value)}
          maxLength={20_000}
        />
        <p className="mt-1.5 text-[12px] leading-relaxed text-subtle">
          This is handed to the review as authoritative direction, so a claim
          you can support gets checked against your evidence instead of being
          escalated for lack of any.
        </p>
        <div className="mt-4 flex flex-wrap gap-2.5">
          <Button
            size="sm"
            onClick={() => onAnswer(value.trim() || null)}
            disabled={!value.trim()}
          >
            Start the review
          </Button>
          <Button
            variant="secondary"
            size="sm"
            onClick={() => onAnswer(null)}
          >
            Nothing to add — start anyway
          </Button>
        </div>
      </TurnCard>
    </>
  );
}
